#!/usr/bin/env python3
"""Safety audit of the DEPLOYED currency model (the TFLite file in the Android assets).
Everything here is OFFLINE and uses SYNTHETIC / scan-derived data unless stated - it is NOT real-world accuracy.
Writes reports/safety_audit.md.  Run:  python safety_audit.py"""
import hashlib, json, os
os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import numpy as np, tensorflow as tf
from common import *
from evaluate import decide

ASSETS = ROOT.parent.parent / "VisionAidObjectDetector" / "android" / "src" / "main" / "assets"
ARR = ROOT / "processed" / "arrays"
sha = lambda p: hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()
L = ["# Currency safety audit (generated by scripts/safety_audit.py)", "",
     "**All numbers below are offline, on SYNTHETIC or scan-derived images. They are not real-world accuracy.**", ""]

# ---- 1. what is really deployed
L += ["## 1. Deployed files and mapping", ""]
tau = json.loads((ASSETS / "currency_thresholds.json").read_text())["accept_threshold"]
same = {k: sha(ASSETS / a) == sha(b) for k, (a, b) in {
    "model assets == runs/": ("currency_classifier.tflite", ROOT / "runs" / "currency_classifier.tflite"),
    "labels assets == labels.json": ("currency_labels.json", ROOT / "labels.json"),
    "thresholds assets == reports/": ("currency_thresholds.json", ROOT / "reports" / "thresholds.json")}.items()}
cfg = json.loads((ROOT / "runs" / "training_config.json").read_text())
same["training class order == labels.json order"] = cfg["classes"] == CLASS_IDS
for k, v in same.items(): L.append(f"- {k}: **{'OK' if v else 'MISMATCH'}**")
it = tf.lite.Interpreter(model_path=str(ASSETS / "currency_classifier.tflite")); it.allocate_tensors()
i, o = it.get_input_details()[0], it.get_output_details()[0]
L += [f"- model input {i['shape'].tolist()} {np.dtype(i['dtype']).name}; output {o['shape'].tolist()} {np.dtype(o['dtype']).name}",
      f"- class order (index: id): " + ", ".join(f"{c['index']}:{c['id']}" for c in LABELS["classes"]),
      f"- accept threshold tau = {tau}", ""]
assert all(same.values()), "deployed files disagree - stop"

def predict(x):
    out = []
    for img in x:
        it.set_tensor(i["index"], img[None].astype(np.float32)); it.invoke(); out.append(it.get_tensor(o["index"])[0])
    return np.array(out)

sets = {}
for n in ("val", "test_sim", "test_collage", "test_neg", "test_unsup"):
    d = np.load(ARR / f"{n}.npz"); sets[n] = (d["x"], d["y"], json.loads((ARR / f"{n}_meta.json").read_text()))
P = {n: predict(v[0]) for n, v in sets.items()}

# ---- 2. old vs new, class-by-class on every set: can an OLD note be announced as NEW (or vice versa)?
L += ["## 2. Old/new separation (series mix-ups at the deployed threshold)", "",
      "| set | note samples | announced correct | announced wrong denomination | of which old<->new series swap | not sure |", "|---|---|---|---|---|---|"]
series = [c["series"] for c in LABELS["classes"]]
for n, (x, y, m) in sets.items():
    top, conf, acc = decide(P[n], tau); isn = y != NO_NOTE_INDEX
    if not isn.any(): continue
    wrong = acc & isn & (top != y); swap = wrong & np.array([series[t] != series[a] for t, a in zip(y, top)])
    L.append(f"| {n} | {int(isn.sum())} | {int((acc & isn & (top == y)).sum())} | {int(wrong.sum())} | {int(swap.sum())} | {int((~acc & isn).sum())} |")
L.append("")

# ---- 3. look-alike pairs
L += ["## 3. Look-alike pairs (new vs old of the same design)", "",
      "Counts are ARGMAX confusions (before the threshold) and wrong ANNOUNCEMENTS (after). `collage` is the only set from a different image source (2 source images per class: unreliable).", "",
      "| pair | set | n(true new) | new->old argmax | new->old announced | n(true old) | old->new argmax | old->new announced |", "|---|---|---|---|---|---|---|---|"]
pairs = [("NEW_1", "OLD_1000"), ("NEW_2", "OLD_2000"), ("NEW_5", "OLD_5000"), ("NEW_10", "OLD_10000")]
for a, b in pairs:
    ia, ib = CLASS_IDS.index(a), CLASS_IDS.index(b)
    for n in ("val", "test_sim", "test_collage"):
        x, y, m = sets[n]; p = P[n]; top, conf, acc = decide(p, tau)
        na, nb = int((y == ia).sum()), int((y == ib).sum())
        L.append(f"| {a} vs {b} | {n} | {na} | {int(((y == ia) & (p.argmax(1) == ib)).sum())} | {int(((y == ia) & acc & (top == ib)).sum())} | {nb} | {int(((y == ib) & (p.argmax(1) == ia)).sum())} | {int(((y == ib) & acc & (top == ia)).sum())} |")
L.append("")
x, y, m = sets["test_collage"]; top, conf, acc = decide(P["test_collage"], tau)
bad = np.where(acc & (top != y))[0]
L += ["Every WRONG ANNOUNCEMENT on test-collage (the most independent set): " + ("; ".join(
      f"true {CLASS_IDS[y[k]]} -> announced {CLASS_IDS[top[k]]} p={conf[k]:.3f} ({m[k]['view']})" for k in bad) or "none"), ""]
nl2 = CLASS_IDS.index("NEW_2"); k2 = np.where(y == nl2)[0]
L.append(f"NEW_2 on test-collage (n={len(k2)}): argmax {dict(zip(*np.unique([CLASS_IDS[t] for t in P['test_collage'][k2].argmax(1)], return_counts=True)))}; announced correctly {int((acc[k2] & (top[k2] == nl2)).sum())}, not sure {int((~acc[k2]).sum())}.")
L.append("")

# ---- 4. calibration
L += ["## 4. Is the confidence calibrated?", "",
      "Reliability = among predictions whose top probability falls in a bin, how often is the top class actually right. ECE = weighted mean |confidence - accuracy|. "
      "A score of 0.965 means 'the model is 96.5 % sure' ONLY if accuracy in that bin is also ~96.5 %.", ""]
bins = [0, .5, .7, .9, .965, .99, 1.0001]
for n in ("val", "test_sim", "test_collage"):
    p = P[n]; y = sets[n][1]; conf = p.max(1); ok = p.argmax(1) == y; ece = 0
    L += [f"**{n}** (n={len(y)}):", "", "| top prob bin | n | mean confidence | accuracy |", "|---|---|---|---|"]
    for lo, hi in zip(bins[:-1], bins[1:]):
        s = (conf >= lo) & (conf < hi)
        if s.any():
            L.append(f"| {lo:.3f}-{min(hi, 1):.3f} | {int(s.sum())} | {conf[s].mean():.3f} | {ok[s].mean():.3f} |"); ece += s.mean() * abs(conf[s].mean() - ok[s].mean())
    L += ["", f"ECE = {ece:.3f}", ""]
L += ["Reading: the model is trained to near-zero loss, so it is over-confident. Where accuracy in a bin is lower than the bin's confidence (see tables, especially the collage set) the score must NOT be read as a probability of being right.", ""]

# ---- 5. threshold review
L += ["## 5. How tau was chosen, and how sensitive it is", "",
      "tau = (first value with zero false notes and zero wrong denominations on VALIDATION) + 0.005 safety margin. "
      "Validation is simulated from the same scans as training, so it cannot prove real-world safety; tau is a starting point only.", "",
      "| tau | val: false note on NO_NOTE | val: wrong denomination | val: announced correctly | test-collage: wrong announced | test-collage: announced correctly |", "|---|---|---|---|---|---|"]
for t in (0.90, 0.93, 0.95, 0.965, 0.98, 0.99, 0.995):
    yv = sets["val"][1]; top, conf, acc = decide(P["val"], t); neg, pos = yv == NO_NOTE_INDEX, yv != NO_NOTE_INDEX
    yc = sets["test_collage"][1]; tc, cc, ac = decide(P["test_collage"], t)
    L.append(f"| {t} | {(acc & neg).sum() / neg.sum():.3f} | {(acc & pos & (top != yv)).sum() / pos.sum():.3f} | {(acc & pos & (top == yv)).sum() / pos.sum():.3f} | {int((ac & (tc != yc)).sum())}/{len(yc)} | {(ac & (tc == yc)).sum() / len(yc):.3f} |")
L.append("")

# ---- 6. NO_NOTE / unknown handling
L += ["## 6. Unknown-input handling", ""]
for n in ("test_neg", "test_unsup"):
    top, conf, acc = decide(P[n], tau); L.append(f"- {n}: n={len(top)}, argmax NO_NOTE {(P[n].argmax(1) == NO_NOTE_INDEX).mean():.3f}, falsely announced a note **{int(acc.sum())}**")
L += ["- The decider also treats NO_NOTE, NaN, wrong-size and non-probability outputs as 'no note' (unit tests `CurrencyDeciderTest`).",
      "- NOT measured: hands holding paper, coloured cards, receipts, other countries' banknotes, screens showing notes - none exist in the data.", ""]

# ---- 7. robustness to the resize implementation (Android averages 4 samples from the full-resolution frame; Python tools use PIL)
L += ["## 7. Sensitivity to the resize method", "",
      "Each test-sim image was upscaled x4 and brought back to 224 with different filters (the app uses a 4-sample box average); argmax agreement with the original prediction:", ""]
x = sets["test_sim"][0][::7]; base = predict(x).argmax(1)
for name, f in (("BOX", Image.BOX), ("BILINEAR", Image.BILINEAR), ("LANCZOS", Image.LANCZOS), ("NEAREST", Image.NEAREST)):
    xs = np.stack([np.asarray(Image.fromarray(a).resize((896, 896), Image.LANCZOS).resize((224, 224), f), dtype=np.uint8) for a in x])
    L.append(f"- {name}: {(predict(xs).argmax(1) == base).mean():.3f} (n={len(x)})")
L.append("")
out = ROOT / "reports" / "safety_audit.md"; out.write_text("\n".join(L) + "\n"); print("\n".join(L))
