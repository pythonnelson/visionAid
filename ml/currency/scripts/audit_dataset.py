#!/usr/bin/env python3
"""Stage A: audits ml/currency/dataset and ml/currency/test. Writes reports/dataset_audit.md.
Does not modify any image."""
import collections, json, pathlib
from common import *

def main():
    rows = []
    for split in ("dataset", "test"):
        for p in list_images(ROOT / split):
            rec = {"path": str(p.relative_to(ROOT)), "split_folder": split, "folder": p.parent.name,
                   "view": view_of(p), "bytes": p.stat().st_size, "md5": md5(p)}
            try:
                im = load_rgb(p); rec.update(w=im.width, h=im.height, fmt=p.suffix.lower().lstrip("."),
                                              dhash=dhash(im), ok=True)
                a = np.asarray(im.convert("L"), dtype=np.float32)
                rec["blank"] = bool(a.std() < 5)
            except Exception as e:
                rec.update(ok=False, error=str(e))
            rows.append(rec)
    good = [r for r in rows if r["ok"]]
    exact = collections.defaultdict(list)
    for r in good: exact[r["md5"]].append(r["path"])
    exact = {k: v for k, v in exact.items() if len(v) > 1}
    near = []
    for i, a in enumerate(good):
        for b in good[i + 1:]:
            if a["md5"] != b["md5"] and hamming(a["dhash"], b["dhash"]) <= 6:
                near.append((a["path"], b["path"], hamming(a["dhash"], b["dhash"])))
    per = collections.Counter((r["folder"], r["view"]) for r in good)
    out = ["# Currency dataset audit (generated by scripts/audit_dataset.py)", "",
           f"Files: {len(rows)} (corrupt: {sum(not r['ok'] for r in rows)}, blank: {sum(r.get('blank', False) for r in good)})", "",
           "| file | view | size | bytes |", "|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['path']} | {r['view']} | {r.get('w')}x{r.get('h')} {r.get('fmt')} | {r['bytes']} |")
    out += ["", "## Files per folder and view", ""]
    for (f, v), n in sorted(per.items()): out.append(f"- {f} / {v}: {n}")
    out += ["", "## Exact duplicates (same bytes)", ""] + ([f"- {v}" for v in exact.values()] or ["- none"])
    out += ["", "## Near duplicates (dhash distance <= 6)", ""] + ([f"- {a} ~ {b} (d={d})" for a, b, d in near] or ["- none"])
    (ROOT / "reports" / "dataset_audit.md").write_text("\n".join(out) + "\n")
    (ROOT / "reports" / "dataset_audit.json").write_text(json.dumps(rows, indent=1))
    print("\n".join(out[:4])); print("exact dups:", exact); print("near dups:", near)

main()
